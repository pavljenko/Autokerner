"""Расстановка с нуля: шрифт без своей расстановки и плотность по форме.

Обычное правило выравнивает расставленный шрифт: эталон белого — медиана
белого самого шрифта. Если полей нет (все нули) или у всех букв одни и те же
поля (как ставит редактор при рисовании), эталона нет: правило оставило бы
всё как есть. Тогда эталон берётся иначе (`spacing._zero_targets`):

1. с букв-образцов (`hand_spaced`): если дизайнер расставил на глаз
   несколько букв (n и o, H и O…), остальные ставятся по ним, а другая
   группа — с той же поправкой к угадыванию;
2. иначе угадывается по форме (`guess`): для прописных и строчных отдельно
   среднее трёх оценок — по промежутку между штамбами H, по четырём буквам
   H, O, n, o и по всем буквам группы с признаками набора (насыщенность,
   ширина, узор). Каждая ошибается по-своему: когда одна промахивается
   (необычная H, полосы, штриховка), две другие её вытягивают.

Числа угадывания (`zero_model`) подобраны 25.10.2026 на 4 095 свободных
шрифтах и 139 профессиональных начертаниях. Медиана ошибки
эталона при проверке, где семьи с общим началом имени не попадают и в
подбор, и в проверку: 10,2/9,6 % (прописные/строчные; одна H — 10,9/9,2),
у шрифтов с необычной H — 24,8/23,6 % (одна H — 29,7/30,8), у 139
профессиональных — 5,9/6,0 %. Образцы n и o, расставленные дизайнером,
дают 6,9/4,2 %. Точнее по форме не угадать:
шрифты с почти одинаковой формой дизайнеры расставляют на 50 % по-разному.
Окно задаёт плотность и числом — средним белым у стороны H, тысячные кегля."""
import math

from .geometry import contours_rect, median
from .zero_model import MODEL

UNSPACED_ZERO = 0.6    # доля букв с нулевыми полями, с которой шрифт считается нерасставленным
UNSPACED_SAME = 0.9    # доля букв с одинаковыми ненулевыми полями (как ставит редактор или генератор)
UNSPACED_EQUAL = 1.0   # поля «одинаковые», если расходятся не больше чем на столько тысячных кегля
GRID_MIN = 0.02        # шаг сетки пиксельного шрифта — от стольких долей кегля


def _rows(edges, y0, y1, n):
    """Чернила по строкам: [(y, [(x0, x1), ...])] по правилу ненулевой обмотки"""
    вышло = []
    for k in range(n):
        y = y0 + (k + 0.5) * (y1 - y0) / n
        пересеч = []
        for низ, верх, ax, ay, bx, by in edges:
            if низ <= y < верх:
                пересеч.append((ax + (bx - ax) * (y - ay) / (by - ay), 1 if by > ay else -1))
        пересеч.sort()
        отрезки, обм, начало = [], 0, None
        for x, d in пересеч:
            было = обм
            обм += d
            if было == 0 and обм != 0:
                начало = x
            elif было != 0 and обм == 0 and начало is not None:
                отрезки.append((начало, x))
                начало = None
        вышло.append((y, отрезки))
    return вышло


# ── формы букв для угадывания плотности ──

NR = 64  # строк на высоту группы при замере буквы
CAPS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
SMALL = "abcdefghijklmnopqrstuvwxyz"
# кириллица того же рисунка — если латинской буквы в шрифте нет
TWINS = {"A": 0x410, "B": 0x412, "C": 0x421, "E": 0x415, "H": 0x41D, "K": 0x41A, "M": 0x41C, "O": 0x41E,
         "P": 0x420, "T": 0x422, "X": 0x425, "a": 0x430, "c": 0x441, "e": 0x435, "o": 0x43E, "p": 0x440,
         "x": 0x445, "y": 0x443, "n": 0x43F}


def letter_shape(glyph, h):
    """Форма буквы в полосе 0..h, в долях h. По средней половине высоты:
    просвет строки (белое между её крайними чернилами), ширина строки,
    штамб (первый отрезок чернил), наибольший промежуток между отрезками,
    число отрезков. По знаку целиком: насыщенность (чернила к габариту),
    ширина, периметр, число контуров. None — знак пуст или почти весь вне полосы"""
    e = glyph.edges
    if not e or h <= 0:
        return None
    xs = [x for _n, _v, ax, _ay, bx, _by in e for x in (ax, bx)]
    x0, x1 = min(xs), max(xs)
    if x1 <= x0:
        return None
    ряды = _rows(e, 0.0, h, NR)
    внутри, снаружи, штамб, отрезков, промежуток = [], [], [], [], []
    for _y, о in ряды[NR // 4:3 * NR // 4]:
        if not о:
            continue
        ш = о[-1][1] - о[0][0]
        снаружи.append(ш)
        внутри.append(ш - sum(b - a for a, b in о))
        штамб.append(о[0][1] - о[0][0])
        отрезков.append(len(о))
        промежуток.append(max([о[k + 1][0] - о[k][1] for k in range(len(о) - 1)] or [0.0]))
    if len(снаружи) < NR // 4:
        return None
    с_чернилами = [о for _y, о in ряды if о]
    чернила = sum(b - a for о in с_чернилами for a, b in о)
    периметр = sum(math.hypot(bx - ax, by - ay) for _n, _v, ax, ay, bx, by in e)
    return {"внутри": sum(внутри) / len(внутри) / h, "снаружи": sum(снаружи) / len(снаружи) / h,
            "штамб": median(штамб) / h, "промежуток": median(промежуток) / h,
            "отрезков": sum(отрезков) / float(len(отрезков)),
            "насыщ": чернила / ((x1 - x0) * len(с_чернилами)), "ширина": (x1 - x0) / h,
            "периметр": периметр / h, "контуров": len(glyph.contours)}


def shapes(master, рост, капитель):
    """Формы латинских букв (или кириллицы того же рисунка): {"upper": {буква: форма},
    "lower": {...}}. Строчный код, ведущий на прописной знак (юникейс), не мерится"""
    вышло = {"upper": {}, "lower": {}}
    прописные = set()
    for регистр, буквы, h in (("upper", CAPS, капитель), ("lower", SMALL, рост)):
        for с in буквы:
            i = master.glyph(ord(с))
            if i is None and с in TWINS:
                i = master.glyph(TWINS[с])
            if i is None or (регистр == "lower" and i in прописные):
                continue
            if регистр == "upper":
                прописные.add(i)
            форма = letter_shape(master.glyphs[i], h)
            if форма:
                вышло[регистр][с] = форма
    return вышло


def _log(x):
    return math.log(max(x, 1e-4))


def _apply(модель, x):
    return модель[0] + sum(w * v for w, v in zip(модель[1], x))


def _letter_medians(модель, формы, лучших=8):
    """Оценки по буквам группы поодиночке: медиана по `лучших` самым надёжным —
    по своей зависимости от просвета буквы и по доле от него"""
    по_просвету, по_доле = [], []
    for с in sorted(формы):
        б = формы[с]
        if с not in модель or б["внутри"] <= 0.005:
            continue
        a, b, разброс, доля, разброс_доли = модель[с]
        x = _log(б["внутри"])
        по_просвету.append((разброс, a + b * x))
        по_доле.append((разброс_доли, x + доля))
    if not по_просвету:
        return [0.0, 0.0]
    return [median([v for _р, v in sorted(по_просвету)[:лучших]]), median([v for _р, v in sorted(по_доле)[:лучших]])]


def _set_features(формы, наклон, рукописный, рост_к_капители):
    """Признаки набора группы — медианы по буквам; None — букв меньше восьми"""
    б = list(формы.values())
    if len(б) < 8:
        return None
    просветы = [v["внутри"] for v in б if v["внутри"] > 0.005]
    return [_log(median(просветы)) if просветы else _log(0.05), _log(median([v["штамб"] for v in б])),
            _log(median([v["насыщ"] for v in б])), _log(median([v["ширина"] for v in б])),
            median([v["отрезков"] for v in б]),
            _log(median([v["периметр"] / max(0.05, v["ширина"]) for v in б])), median([v["контуров"] for v in б]),
            наклон, 1.0 if рукописный else 0.0, рост_к_капители]


def guess(master, рост, капитель, рукописный=False, формы=None):
    """Плотность по форме — белое на строку полосы, единицы шрифта:
    {"upper": …, "lower": …}. Среднее трёх оценок (в логарифмах, `zero_model`):
    по промежутку H, по четырём буквам H, O, n, o и по всем буквам группы с
    признаками набора; оценка, которую не замерить, не в счёт. Группы, для
    которой не вышло ни одной, в ответе нет"""
    формы = формы or shapes(master, рост, капитель)
    наклон = abs(float(getattr(master, "italic_angle", 0.0) or 0.0)) / 10
    # без строчных (шрифт из одних прописных) рост — та же капитель: доля роста — как у подбора
    рост_к_капители = _log(рост / капитель) if формы["lower"] else MODEL["x_to_cap"]
    H = формы["upper"].get("H")
    по_H = [_log(H["промежуток"])] if H and H["промежуток"] > 0 else None
    четыре = []
    for с, регистр in (("H", "upper"), ("O", "upper"), ("n", "lower"), ("o", "lower")):
        б = формы[регистр].get(с)
        if not б:
            четыре = None
            break
        четыре += [_log(б["внутри"]), _log(б["снаружи"]), _log(max(б["штамб"], 0.01))]
    if четыре is not None:
        четыре += [наклон, рост_к_капители]
    вышло = {}
    for регистр, h in (("upper", капитель), ("lower", рост)):
        модель = MODEL[регистр]
        оценки = []
        if по_H:
            оценки.append(_apply(модель["H"], по_H))
        if четыре:
            оценки.append(_apply(модель["four"], четыре))
        набор = _set_features(формы[регистр], наклон, рукописный, рост_к_капители)
        if набор:
            оценки.append(_apply(модель["set"], набор + _letter_medians(модель["letters"], формы[регистр])))
        if оценки:
            y = min(max(sum(оценки) / len(оценки), модель["limits"][0]), модель["limits"][1])
            вышло[регистр] = math.exp(y) * h
    return вышло


# буквы-образцы: их дизайнер расставляет на глаз первыми (кириллица — п о н и Н О П И)
HAND_LETTERS = "nohumilHOINU\u043f\u043e\u043d\u0438\u041d\u041e\u041f\u0418"
HAND_MIN = 5.0     # поле образца отличается от общего больше чем на столько тысячных кегля
HAND_MAX = 0.4     # образцов больше этой доли букв — это уже своя расстановка, а не образцы


def hand_spaced(master):
    """Буквы-образцы, расставленные дизайнером в шрифте без своей расстановки:
    поле не такое, как у большинства букв (нулевое или общее). Остальные буквы
    тогда ставятся по ним. → {имя знака: (левое своё, правое своё)}; пусто —
    образцов нет. Смотрятся только `HAND_LETTERS`: случайный знак с нестандартным
    полем (крючок j, вынос f) образцом не станет"""
    допуск = HAND_MIN * master.upm / 1000.0
    поля, образцы = {}, set()
    for с in CAPS + SMALL + "".join(chr(к) for к in range(0x410, 0x450)):
        i = master.glyph(ord(с))
        if i is None or i in поля:
            continue
        рамка = contours_rect(master.contours(i))
        if рамка is None:
            continue
        поля[i] = (рамка[0], master.advance(i) - рамка[2])
        if с in HAND_LETTERS:
            образцы.add(i)
    if len(поля) < 10:
        return {}
    л0 = median([л for л, _ in поля.values()])
    п0 = median([п for _, п in поля.values()])
    свои = {i: (abs(л - л0) > допуск, abs(п - п0) > допуск) for i, (л, п) in поля.items()}
    вышло = {master.name(i): свои[i] for i in образцы if any(свои[i])}
    if sum(1 for i in свои if any(свои[i])) > HAND_MAX * len(поля):
        return {}
    return вышло


def _grid(master, знаки):
    """Пиксельный шрифт: почти все отрезки контуров — целое число шагов
    крупной сетки (шаг от `GRID_MIN` кегля; сетка может быть со сдвигом)"""
    отрезки = []
    for i in знаки:
        for контур in master.contours(i):
            прежняя = None
            for команда in контур.commands:
                точки = [p for p in команда[1:] if isinstance(p, tuple) and len(p) == 2]
                if not точки:
                    continue
                p = точки[-1]
                if прежняя is not None:
                    for d in (abs(p[0] - прежняя[0]), abs(p[1] - прежняя[1])):
                        if d > 0.5:
                            отрезки.append(d)
                прежняя = p
    if len(отрезки) < 40:
        return False
    допуск = max(1.0, master.upm / 1000.0)
    for шаг in range(int(master.upm * 0.2), max(2, int(master.upm * GRID_MIN)) - 1, -1):
        на_сетке = sum(1 for d in отрезки if abs(d - round(d / шаг) * шаг) <= допуск)
        if на_сетке >= 0.95 * len(отрезки):
            return True
    return False


def unspaced(master, letters="abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ"):
    """Шрифт без своей расстановки: у большинства букв поля нулевые или у
    почти всех одинаковые (как ставит редактор или генератор, пока буквы не
    расставлены). Моноширинные и пиксельные шрифты сюда не попадают: у них
    одинаковые поля — замысел (замер 25.10.2026: в выборке из 321 шрифта так
    выглядели 22 пиксельных и моноширинных)"""
    допуск = UNSPACED_EQUAL * master.upm / 1000.0
    поля, знаки, ширины = [], [], set()
    for с in letters:
        i = master.glyph(ord(с))
        if i is None:
            continue
        рамка = contours_rect(master.contours(i))
        if рамка is None:
            continue
        поля.append((рамка[0], master.advance(i) - рамка[2]))
        знаки.append(i)
        ширины.add(master.advance(i))
    if len(поля) < 10 or len(ширины) <= 2:
        return False
    нули = sum(1 for л, п in поля if abs(л) <= допуск and abs(п) <= допуск)
    л0 = median([л for л, _ in поля])
    п0 = median([п for _, п in поля])
    равные = sum(1 for л, п in поля if abs(л - л0) <= допуск and abs(п - п0) <= допуск)
    if нули < UNSPACED_ZERO * len(поля) and равные < UNSPACED_SAME * len(поля):
        return False
    return not _grid(master, знаки)

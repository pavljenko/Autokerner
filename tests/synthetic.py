"""Маленький рисованный шрифт для проверок без чужих файлов: прямоугольники
и восьмиугольники вместо букв"""

from autokerner.geometry import Contour
from autokerner.model import Glyph, Master


def прямоугольник(x0, y0, x1, y1):
    return Contour([("moveTo", (x0, y0)), ("lineTo", (x1, y0)), ("lineTo", (x1, y1)),
                    ("lineTo", (x0, y1)), ("closePath",)])


def круг(x0, y0, x1, y1, срез=0.3):
    dx, dy = (x1 - x0) * срез, (y1 - y0) * срез
    точки = [(x0 + dx, y0), (x1 - dx, y0), (x1, y0 + dy), (x1, y1 - dy),
             (x1 - dx, y1), (x0 + dx, y1), (x0, y1 - dy), (x0, y0 + dy)]
    команды = [("moveTo", точки[0])] + [("lineTo", p) for p in точки[1:]] + [("closePath",)]
    return Contour(команды)


def мастер(жир=80, пробел=600, широкая_u=True, weight=400.0):
    s = жир
    знаки = [
        Glyph(".notdef", [], 500, [прямоугольник(50, 0, 450, 700)]),
        Glyph("space", [0x20], пробел, []),
        Glyph("n", [0x6E], 500, [прямоугольник(50, 0, 50 + s, 500), прямоугольник(450 - s, 0, 450, 500),
                                 прямоугольник(50, 500 - s, 450, 500)]),
        Glyph("u", [0x75], 600 if широкая_u else 500,
              [прямоугольник(150 if широкая_u else 50, 0, (150 if широкая_u else 50) + s, 500),
               прямоугольник((550 if широкая_u else 450) - s, 0, 550 if широкая_u else 450, 500),
               прямоугольник(150 if широкая_u else 50, 0, 550 if широкая_u else 450, s)]),
        Glyph("o", [0x6F], 520, [круг(40, -10, 480, 510)]),
        Glyph("x", [0x78], 480, [прямоугольник(30, 0, 450, 500)]),
        Glyph("H", [0x48], 640, [прямоугольник(60, 0, 60 + s, 700), прямоугольник(580 - s, 0, 580, 700),
                                 прямоугольник(60, 320, 580, 320 + s)]),
        Glyph("O", [0x4F], 720, [круг(40, -10, 680, 710)]),
        Glyph("T", [0x54], 600, [прямоугольник(10, 700 - s, 590, 700),
                                 прямоугольник(300 - s / 2, 0, 300 + s / 2, 700)]),
        Glyph("period", [0x2E], 240, [прямоугольник(70, 0, 70 + s + 20, s + 20)]),
        Glyph("one", [0x31], 560, [прямоугольник(240, 0, 240 + s, 700)]),
        Glyph("two", [0x32], 560, [прямоугольник(60, 0, 500, 700)]),
    ]
    return Master(1000, знаки, x_height=500, cap_height=700, label="синтетика %d" % жир,
                  weight=weight)
